import assert from 'node:assert/strict';
import {mkdtempSync} from 'node:fs';import os from 'node:os';import path from 'node:path';
import {createRequire} from 'node:module';
import {createProductCatalog} from '../server/services/product-catalog.ts';
import {createProductDrawings, selectProductionDrawings} from '../server/services/product-drawings.ts';
const require=createRequire(new URL('../server/package.json',import.meta.url));
const {PDFDocument,degrees}=require('pdf-lib');
const pdf=await PDFDocument.create();pdf.addPage([842,595]);const content=Buffer.from(await pdf.save());
const store=createProductCatalog(mkdtempSync(path.join(os.tmpdir(),'product-drawings-')));
const admin={id:'e1',name:'工程',role:'user',permissions:['product_drawing_manage']};
const reader={id:'p1',name:'产线',role:'user',permissions:['production']};
const refs=[{id:'s1',serialNo:'P1',customer:'甲',customerPartNo:'A',model:'M',categoryKey:'gear',categoryName:'成品',versionNo:1,fields:{}}];
store.reconcileStandards(refs);const product=store.list(refs)[0];
const drawings=createProductDrawings(store);
const input={drawingNo:'D1',version:'A1',filename:'图纸.pdf',kind:'pdf' as const,standardIds:[]};
try {
 await assert.rejects(()=>drawings.upload(product,input,content,reader),/权限/);
 const draft=await drawings.upload(product,input,content,admin);
 assert.equal(drawings.list(product.id,reader).length,0);
 assert.throws(()=>drawings.read(product.id,draft.id,reader),/权限/);
 drawings.publish(product,draft.id,admin);
 assert.equal(drawings.list(product.id,reader).length,1);
 assert.throws(()=>drawings.read('wrong',draft.id,admin),/不存在/);
 const newer=await drawings.upload(product,{...input,version:'A2'},content,admin);
 drawings.publish(product,newer.id,admin);
 assert.equal(drawings.list(product.id,reader).length,1);
 assert.equal(drawings.list(product.id,reader)[0].version,'A2');
 await assert.rejects(()=>drawings.upload(product,{...input,version:'bad',standardIds:['other-product']},content,admin),/客户标准/);
 await assert.rejects(()=>drawings.upload(product,{...input,version:'bad'},Buffer.from('%PDF-not-real'),admin),/PDF/);
 const own=await drawings.upload(product,{...input,version:'C1',standardIds:['s1']},content,admin);
 drawings.publish(product,own.id,admin);
 assert.equal(selectProductionDrawings(drawings.list(product.id,reader),'s1')[0].id,own.id);
 assert.equal(selectProductionDrawings(drawings.list(product.id,reader),'s2')[0].id,newer.id);
 const printed=await drawings.print(product,newer.id,reader);
 assert.equal((await PDFDocument.load(printed)).getPageCount(),1);
 assert.equal((store.db.prepare("SELECT count(*) n FROM product_file_events WHERE action='print'").get() as {n:number}).n,1);
 drawings.retire(product,newer.id,admin);
 assert.throws(()=>drawings.read(product.id,newer.id,reader),/权限/);
 const rotated=await PDFDocument.create();const page=rotated.addPage([600,800]);page.drawText('Rotated crop');page.setCropBox(50,50,500,700);page.setRotation(degrees(90));
 const rotateFile=await drawings.upload(product,{...input,drawingNo:'ROTATE',version:'R1'},Buffer.from(await rotated.save()),admin);drawings.publish(product,rotateFile.id,admin);
 const printRotated=await PDFDocument.load(await drawings.print(product,rotateFile.id,reader));
 assert.equal(printRotated.getPage(0).getRotation().angle,90,'打印保留页面方向');
 assert.equal(printRotated.getPage(0).getCropBox().height,700,'打印保持旋转后的可见宽度');
 assert.equal(printRotated.getPage(0).getCropBox().width,540,'打印保留裁剪范围并增加40pt受控页脚');
 const annotated=await PDFDocument.create();const apage=annotated.addPage([842,595]);apage.drawText('Body');
 const field=annotated.getForm().createTextField('dimension');field.setText('CRITICAL DIMENSION 10mm');field.addToPage(apage,{x:50,y:300,width:300,height:40});
 const formFile=await drawings.upload(product,{...input,drawingNo:'FORM',version:'F1'},Buffer.from(await annotated.save()),admin);drawings.publish(product,formFile.id,admin);
 const printForm=await PDFDocument.load(await drawings.print(product,formFile.id,reader));
 assert.equal(printForm.getForm().getFields().length,1,'打印不能丢失可见表单/批注层');
 assert.ok(printForm.getPage(0).node.Annots()?.size());
 const inactive={...product,productionAvailable:false};
 await assert.rejects(()=>drawings.print(inactive,newer.id,reader),/不能打印/);
 let live:typeof admin|null=admin;
 const guarded=createProductDrawings(store,()=>live);
 const pending=guarded.upload(product,{...input,drawingNo:'REVOKE',version:'V1'},content,admin);
 live=null;await assert.rejects(()=>pending,/登录状态/);
 assert(!drawings.list(product.id,admin).some(file=>file.drawingNo==='REVOKE'));
 const labeled=await drawings.upload(product,{...input,drawingNo:'RD-T008 客户补充说明（有齿轮）'},content,admin);assert.equal(labeled.drawingNo,'RD-T008 客户补充说明（有齿轮）');
 for(const drawingNo of ['   ','RD-T008/客户','RD-T008\n客户'])await assert.rejects(()=>drawings.upload(product,{...input,drawingNo},content,admin),/图号/);
 console.log('product drawings tests passed');
}finally{store.close();}
