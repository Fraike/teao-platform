import assert from 'node:assert/strict';
import {mkdtempSync} from 'node:fs';
import path from 'node:path';
import os from 'node:os';
process.env.DATA_DIR=mkdtempSync(path.join(os.tmpdir(),'standard-import-confirm-'));
const s=await import('../server/services/standard-store.js');s.initDB();
const user={id:'admin',name:'管理员'};
const record={serialNo:'SP-I',customer:'客户',model:'RD-T001',categoryKey:'gear_damper',fields:{torque_standard:'12-18'}};
try {
 const invalid=[record,{...record,serialNo:'SP-bad',categoryKey:'invalid'}];
 const p=s.previewStandardImport(invalid,user);assert.equal(p.token,null);assert.equal(p.errors.length,1);
 await assert.rejects(()=>s.confirmStandardImport(invalid,user,'none'),e=>e.status===400);
 assert.equal(s.listStandards().length,0);
 let valid=s.previewStandardImport([record],user);
 s.createStandard({...record,serialNo:'other'},user);
 await assert.rejects(()=>s.confirmStandardImport([record],user,valid.token),e=>e.status===409);
 valid=s.previewStandardImport([record],user);
 await assert.rejects(()=>s.confirmStandardImport([record],{id:'wrong',name:'其他'},valid.token),e=>e.status===409);
 await s.confirmStandardImport([record],user,valid.token);
 await assert.rejects(()=>s.confirmStandardImport([record],user,valid.token),e=>e.status===409);
 const again=s.previewStandardImport([record,{...record,customer:'其他客户'}],user);assert.equal(again.skipped,1);
 const result=await s.confirmStandardImport([record,{...record,customer:'其他客户'}],user,again.token);
 assert.equal(result.inserted,1);assert.equal(result.skipped,1);
 const revokedRecord={...record,serialNo:'revoked'};
 const revoked=s.previewStandardImport([revokedRecord],user);
 await assert.rejects(()=>s.confirmStandardImport([revokedRecord],user,revoked.token,()=>{throw Object.assign(new Error('权限已失效'),{status:403});}),e=>e.status===403);
 assert(!s.listStandards().some(x=>x.serialNo==='revoked'));
 const annotated={...record,serialNo:'SP-comment',comments:[{fieldKey:'test_standard',fieldLabel:'测试范围',author:'原作者',text:'2024.6.19 15-22改为15-25',cell:'F15',changedAt:'2024-06-19'}]};
 const cp=s.previewStandardImport([annotated],user);
 await s.confirmStandardImport([annotated],user,cp.token);
 const row=s.listStandards().find(x=>x.serialNo==='SP-comment');
 const history=s.getStandard(row.id,{onlyPublished:true}).changes.find(c=>c.sourceCell==='F15');
 assert.equal(history.author,'原作者');assert.equal(history.changedAt,'2024-06-19');assert.equal(history.description,annotated.comments[0].text);
 const variants=[{...record,serialNo:'SP-project',fields:{marking:'型号E115'}},{...record,serialNo:'SP-project',fields:{marking:'A02'}}];
 const vp=s.previewStandardImport(variants,user);assert.equal(vp.skipped,0);
 assert.equal((await s.confirmStandardImport(variants,user,vp.token)).inserted,2);
 assert.equal(s.previewStandardImport(variants,user).skipped,2);
 console.log('standard import confirmation regression passed');
} finally {s.closeDB();}
