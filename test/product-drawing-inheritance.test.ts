import assert from 'node:assert/strict';
import {mkdtempSync,readdirSync} from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {createRequire} from 'node:module';
import {createProductCatalog} from '../server/services/product-catalog.ts';
import {createProductDrawings} from '../server/services/product-drawings.ts';
import {publishedProductReferences} from '../server/services/product-reference.ts';
process.env.DATA_DIR=mkdtempSync(path.join(os.tmpdir(),'drawing-copy-'));
const standards=await import('../server/services/standard-store.js');
standards.initDB();
const store=createProductCatalog(process.env.DATA_DIR);
const drawings=createProductDrawings(store);
const require=createRequire(new URL('../server/package.json',import.meta.url));
const {PDFDocument}=require('pdf-lib');
const pdf=await PDFDocument.create();pdf.addPage([842,595]);const bytes=Buffer.from(await pdf.save());
const admin={id:'admin',name:'工程',role:'admin',permissions:[]};
const reader={id:'reader',name:'产线',role:'user',permissions:['production']};
const payload={serialNo:'SP-SOURCE',customer:'甲',model:'RD-T008-28',categoryKey:'gear_damper',fields:{}};
const reconcile=()=>{const refs=publishedProductReferences(standards.getDB());store.reconcileStandards(refs);return store.list(refs);};
try {
 const source=standards.createStandard(payload,admin);
 const original=reconcile().find(p=>p.internalNumber===payload.serialNo)!;
 const common=await drawings.upload(original,{drawingNo:'RD-T008',version:'A1',filename:'通用.pdf',kind:'pdf',standardIds:[],structure:'geared'},bytes,admin);
 drawings.publish(original,common.id,admin);
 const client=await drawings.upload(original,{drawingNo:'RD-T008-CLIENT',version:'A1',filename:'客户.pdf',kind:'pdf',standardIds:[source.id]},bytes,admin);
 drawings.publish(original,client.id,admin);
 const draft=standards.createStandard({...payload,serialNo:'SP-COPY',customer:'乙',copyDrawingSourceId:source.id},{...admin,role:'user'});
 assert(!reconcile().some(p=>p.internalNumber==='SP-COPY'),'draft must not expose inherited drawings');
 standards.updateStandard(draft.id,{...payload,serialNo:'SP-COPY',customer:'乙',versionId:draft.versions[0].id,revision:draft.versions[0].revision},admin);
 const copied=reconcile().find(p=>p.internalNumber==='SP-COPY')!;
 const inherited=drawings.list(copied.id,reader);
 assert.equal(inherited.length,1,'published copy inherits only general drawings');
 assert.equal(inherited[0].drawingNo,'RD-T008');assert.equal(inherited[0].status,'published');
 assert.deepEqual(drawings.read(copied.id,inherited[0].id,reader).bytes,bytes);
 reconcile();assert.equal(drawings.list(copied.id,reader).length,1,'reconciliation is idempotent');
 assert.equal(readdirSync(path.join(process.env.DATA_DIR,'product-blobs')).length,1,'all associations share the same PDF bytes');
 standards.createStandard({...payload,serialNo:'SP-NO-COPY'},admin);
 assert.equal(drawings.list(reconcile().find(p=>p.internalNumber==='SP-NO-COPY')!.id,reader).length,0);
 const next=standards.createStandard({...payload,serialNo:'SP-NEXT',copyDrawingSourceId:draft.id},admin);
 assert.equal(drawings.list(reconcile().find(p=>p.internalNumber==='SP-NEXT')!.id,reader).length,1);assert(next.id);
 drawings.retire(copied,inherited[0].id,admin);reconcile();assert.equal(drawings.list(copied.id,reader).length,0,'refresh must not revive a retired inherited drawing');
 assert.throws(()=>standards.createStandard({...payload,copyDrawingSourceId:'missing'},admin),/来源/);
 console.log('published standard copies inherit general drawings only, without duplicate blobs');
} finally {store.close();standards.closeDB();}
